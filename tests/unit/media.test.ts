import { describe, expect, it } from 'vitest';
import { fitWithin, sha256, sourceDimensions, runBounded } from '../../src/media/processing';

describe('bounded photo processing', () => {
  it('preserves aspect ratio without upscaling', () => {
    expect(fitWithin(3200, 1600, 2000)).toEqual({ width: 2000, height: 1000 });
    expect(fitWithin(80, 160, 400)).toEqual({ width: 80, height: 160 });
    expect(() => fitWithin(0, 100, 400)).toThrow();
  });
  it('hashes generated bytes exactly', async () => {
    expect(await sha256(new TextEncoder().encode('hello'))).toBe(
      '2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824',
    );
  });
  it('reads PNG dimensions before decoding and rejects huge/truncated headers', () => {
    const header = new Uint8Array(24);
    header.set([137, 80, 78, 71, 13, 10, 26, 10]);
    header.set([73, 72, 68, 82], 12);
    const view = new DataView(header.buffer);
    view.setUint32(16, 3000);
    view.setUint32(20, 2000);
    expect(sourceDimensions(header)).toEqual({ width: 3000, height: 2000 });
    view.setUint32(16, 50000);
    expect(() => sourceDimensions(header)).toThrow();
    expect(() => sourceDimensions(header.slice(0, 18))).toThrow();
  });
  it('bounds concurrent work and waits for running work after a failure', async () => {
    let active = 0;
    let peak = 0;
    const finished: number[] = [];
    await expect(
      runBounded([0, 1, 2, 3, 4], 2, async (value) => {
        peak = Math.max(peak, ++active);
        await new Promise((resolve) => setTimeout(resolve, 5));
        --active;
        finished.push(value);
        if (value === 0) throw new Error('synthetic failure');
      }),
    ).rejects.toThrow('synthetic failure');
    expect(peak).toBe(2);
    expect(active).toBe(0);
    expect(finished.sort()).toEqual([0, 1]);
  });
  it('does not start work after cancellation', async () => {
    const controller = new AbortController();
    controller.abort();
    let calls = 0;
    await expect(
      runBounded(
        [1],
        2,
        async () => {
          ++calls;
        },
        controller.signal,
      ),
    ).rejects.toThrow();
    expect(calls).toBe(0);
  });
});
